CREATE SCHEMA IF NOT EXISTS squad_chat;
CREATE TABLE IF NOT EXISTS squad_chat.sq_chat_session
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id               VARCHAR(64)  NOT NULL,
    user_id                  BIGINT       NOT NULL,
    agent_id                 VARCHAR(80)  NOT NULL,
    title                    VARCHAR(120) NOT NULL DEFAULT '新对话',
    title_source             VARCHAR(16)  NOT NULL DEFAULT 'AUTO' CHECK (title_source IN ('AUTO', 'MANUAL')),
    version                  BIGINT       NOT NULL DEFAULT 0,
    has_messages             BOOLEAN      NOT NULL DEFAULT FALSE,
    first_interaction_id     VARCHAR(64),
    pending_initial_input_id VARCHAR(64),
    pending_initial_title    VARCHAR(120),
    last_activity_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    execution_status         VARCHAR(16)  NOT NULL DEFAULT 'UNKNOWN' CHECK (execution_status IN
                                                                            ('UNKNOWN', 'IDLE', 'QUEUED', 'RUNNING',
                                                                             'COMPLETED', 'FAILED', 'WAITING',
                                                                             'INTERRUPTED')),
    execution_cursor         BIGINT       NOT NULL DEFAULT 0,
    input_cursor             BIGINT       NOT NULL DEFAULT 0,
    execution_observed_at TIMESTAMPTZ(3),
    last_status_check_at TIMESTAMPTZ(3),
    creator_id               BIGINT       NOT NULL DEFAULT 0,
    creator_name             VARCHAR(50)  NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updater_id          BIGINT       NOT NULL DEFAULT 0,
    last_updater_name        VARCHAR(50)  NOT NULL DEFAULT '',
    last_update_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    del_flag                 CHAR(1)      NOT NULL DEFAULT '0' CHECK (del_flag IN ('0', '1')),
    UNIQUE (user_id, session_id)
);
CREATE INDEX IF NOT EXISTS idx_chat_session_user_activity ON squad_chat.sq_chat_session
    (user_id, last_activity_time DESC, id DESC) WHERE del_flag = '0';
CREATE INDEX IF NOT EXISTS idx_chat_session_check ON squad_chat.sq_chat_session
    (last_status_check_at, id) WHERE del_flag = '0';
