CREATE OR REPLACE FUNCTION sq_touch_last_update_time()
    RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.last_update_time IS NOT DISTINCT FROM OLD.last_update_time THEN
        NEW.last_update_time := statement_timestamp() AT TIME ZONE 'UTC';
    END IF;
    RETURN NEW;
END;
$$;

