-- 管理接口权限规则：接口路径与所需功能权限的对应关系，由 Gateway 动态加载。
CREATE TABLE IF NOT EXISTS squad_user.sq_permission_route
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code VARCHAR(64) NOT NULL REFERENCES squad_user.sq_permission(code),
    http_method VARCHAR(8) NOT NULL,
    path_pattern VARCHAR(200) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    creator_id BIGINT NOT NULL DEFAULT 0,
    creator_name VARCHAR(50) NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updater_id BIGINT NOT NULL DEFAULT 0,
    last_updater_name VARCHAR(50) NOT NULL DEFAULT '',
    last_update_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (http_method, path_pattern)
);
COMMENT ON TABLE squad_user.sq_permission_route IS '管理接口权限规则';
COMMENT ON COLUMN squad_user.sq_permission_route.id IS '存储主键';
COMMENT ON COLUMN squad_user.sq_permission_route.permission_code IS '所需功能权限编码';
COMMENT ON COLUMN squad_user.sq_permission_route.http_method IS '请求方法';
COMMENT ON COLUMN squad_user.sq_permission_route.path_pattern IS '管理前缀后的路径正则';
COMMENT ON COLUMN squad_user.sq_permission_route.sort_order IS '匹配顺序';
COMMENT ON COLUMN squad_user.sq_permission_route.creator_id IS '创建人ID';
COMMENT ON COLUMN squad_user.sq_permission_route.creator_name IS '创建人名称';
COMMENT ON COLUMN squad_user.sq_permission_route.create_time IS '创建时间';
COMMENT ON COLUMN squad_user.sq_permission_route.last_updater_id IS '最后更新人ID';
COMMENT ON COLUMN squad_user.sq_permission_route.last_updater_name IS '最后更新人名称';
COMMENT ON COLUMN squad_user.sq_permission_route.last_update_time IS '最后更新时间';

