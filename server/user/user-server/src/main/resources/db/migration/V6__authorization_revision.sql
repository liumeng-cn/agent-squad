-- 授权变更使用版本条件更新裁决并发，不使用悲观查询锁。
CREATE TABLE IF NOT EXISTS squad_user.sq_rbac_revision
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0,
    creator_id BIGINT NOT NULL DEFAULT 0,
    creator_name VARCHAR(50) NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updater_id BIGINT NOT NULL DEFAULT 0,
    last_updater_name VARCHAR(50) NOT NULL DEFAULT '',
    last_update_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE squad_user.sq_rbac_revision IS '授权变更版本';
COMMENT ON COLUMN squad_user.sq_rbac_revision.id IS '存储主键';
COMMENT ON COLUMN squad_user.sq_rbac_revision.code IS '版本作用域';
COMMENT ON COLUMN squad_user.sq_rbac_revision.version IS '并发校验版本';
COMMENT ON COLUMN squad_user.sq_rbac_revision.creator_id IS '创建人ID';
COMMENT ON COLUMN squad_user.sq_rbac_revision.creator_name IS '创建人名称';
COMMENT ON COLUMN squad_user.sq_rbac_revision.create_time IS '创建时间';
COMMENT ON COLUMN squad_user.sq_rbac_revision.last_updater_id IS '最后更新人ID';
COMMENT ON COLUMN squad_user.sq_rbac_revision.last_updater_name IS '最后更新人名称';
COMMENT ON COLUMN squad_user.sq_rbac_revision.last_update_time IS '最后更新时间';
INSERT INTO squad_user.sq_rbac_revision (code)
VALUES ('authorization')
ON CONFLICT (code) DO NOTHING;
