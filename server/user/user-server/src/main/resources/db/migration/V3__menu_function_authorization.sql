CREATE TABLE IF NOT EXISTS squad_user.sq_menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id VARCHAR(64) NOT NULL UNIQUE,
    parent_menu_id VARCHAR(64) REFERENCES squad_user.sq_menu(menu_id),
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(64) NOT NULL,
    type VARCHAR(16) NOT NULL CHECK (type IN ('DIRECTORY', 'PAGE')),
    route_name VARCHAR(64),
    route_path VARCHAR(200),
    icon VARCHAR(64),
    sort_order INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    version BIGINT NOT NULL DEFAULT 0,
    creator_id BIGINT NOT NULL DEFAULT 0,
    creator_name VARCHAR(50) NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updater_id BIGINT NOT NULL DEFAULT 0,
    last_updater_name VARCHAR(50) NOT NULL DEFAULT '',
    last_update_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_menu_parent ON squad_user.sq_menu(parent_menu_id);
CREATE TABLE IF NOT EXISTS squad_user.sq_role_menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id VARCHAR(64) NOT NULL REFERENCES squad_user.sq_role(role_id),
    menu_id VARCHAR(64) NOT NULL REFERENCES squad_user.sq_menu(menu_id),
    stage VARCHAR(16) NOT NULL CHECK (stage IN ('DRAFT', 'APPLIED')),
    creator_id BIGINT NOT NULL DEFAULT 0,
    creator_name VARCHAR(50) NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updater_id BIGINT NOT NULL DEFAULT 0,
    last_updater_name VARCHAR(50) NOT NULL DEFAULT '',
    last_update_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(role_id, menu_id, stage)
);
CREATE INDEX IF NOT EXISTS idx_role_menu_menu ON squad_user.sq_role_menu(menu_id);
ALTER TABLE squad_user.sq_permission ADD COLUMN IF NOT EXISTS menu_id VARCHAR(64) REFERENCES squad_user.sq_menu(menu_id);
