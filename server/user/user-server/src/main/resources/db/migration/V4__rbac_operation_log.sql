-- 授权操作日志：仅追加，随授权变更同事务写入。
CREATE TABLE IF NOT EXISTS squad_user.sq_rbac_log
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation VARCHAR(32) NOT NULL,
    target_id VARCHAR(64) NOT NULL,
    summary VARCHAR(4000) NOT NULL,
    creator_id BIGINT NOT NULL DEFAULT 0,
    creator_name VARCHAR(50) NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE squad_user.sq_rbac_log IS '授权操作日志';
COMMENT ON COLUMN squad_user.sq_rbac_log.id IS '存储主键';
COMMENT ON COLUMN squad_user.sq_rbac_log.operation IS '操作类型';
COMMENT ON COLUMN squad_user.sq_rbac_log.target_id IS '操作目标业务ID';
COMMENT ON COLUMN squad_user.sq_rbac_log.summary IS '角色或权限变更摘要';
COMMENT ON COLUMN squad_user.sq_rbac_log.creator_id IS '操作人ID';
COMMENT ON COLUMN squad_user.sq_rbac_log.creator_name IS '操作人名称';
COMMENT ON COLUMN squad_user.sq_rbac_log.create_time IS '操作时间';

CREATE INDEX IF NOT EXISTS idx_rbac_log_target ON squad_user.sq_rbac_log (target_id, create_time);
