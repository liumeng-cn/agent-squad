CREATE SCHEMA IF NOT EXISTS squad_user;
CREATE
SEQUENCE IF NOT EXISTS squad_user.user_business_id_seq START
WITH 100000;
CREATE TABLE IF NOT EXISTS squad_user.sq_user
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL UNIQUE,
    username          VARCHAR(64)  NOT NULL UNIQUE,
    phone             VARCHAR(20)  NOT NULL UNIQUE,
    display_name      VARCHAR(100) NOT NULL DEFAULT '',
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    auth_version      BIGINT       NOT NULL DEFAULT 0,
    version           BIGINT       NOT NULL DEFAULT 0,
    creator_id        BIGINT       NOT NULL DEFAULT 0,
    creator_name      VARCHAR(50)  NOT NULL DEFAULT '',
    create_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_updater_id   BIGINT       NOT NULL DEFAULT 0,
    last_updater_name VARCHAR(50)  NOT NULL DEFAULT '',
    last_update_time TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    del_flag          CHAR(1)      NOT NULL DEFAULT '0' CHECK (del_flag IN ('0', '1'))
);
COMMENT ON TABLE squad_user.sq_user IS '用户账号';
COMMENT ON COLUMN squad_user.sq_user.id IS '存储主键';
COMMENT ON COLUMN squad_user.sq_user.user_id IS '用户业务ID';
COMMENT ON COLUMN squad_user.sq_user.username IS '自动生成的用户名';
COMMENT ON COLUMN squad_user.sq_user.phone IS '注册手机号';
COMMENT ON COLUMN squad_user.sq_user.display_name IS '用户自定义昵称';
COMMENT ON COLUMN squad_user.sq_user.status IS '账号状态ACTIVE正常DISABLED禁用';
COMMENT ON COLUMN squad_user.sq_user.auth_version IS '认证版本';
COMMENT ON COLUMN squad_user.sq_user.version IS '编辑乐观锁版本';
COMMENT ON COLUMN squad_user.sq_user.creator_id IS '创建人ID';
COMMENT ON COLUMN squad_user.sq_user.creator_name IS '创建人姓名';
COMMENT ON COLUMN squad_user.sq_user.create_time IS '创建时间';
COMMENT ON COLUMN squad_user.sq_user.last_updater_id IS '最后更新人ID';
COMMENT ON COLUMN squad_user.sq_user.last_updater_name IS '最后更新人姓名';
COMMENT ON COLUMN squad_user.sq_user.last_update_time IS '最后更新时间';
COMMENT ON COLUMN squad_user.sq_user.del_flag IS '删除标记0否1是';
