import { describe, expect, it } from 'vitest'
import {
  buildTestArguments,
  fieldsFromSchema,
  isValidBodyTemplate,
  placeholdersIn,
  schemaFromFields,
  validateFields,
  type ParamField,
} from './toolSchema'

const field = (overrides: Partial<ParamField>): ParamField => ({
  name: 'keyword',
  type: 'string',
  required: false,
  description: '',
  enumValues: '',
  ...overrides,
})

describe('schemaFromFields', () => {
  it('builds an object schema with required list, enums and array items', () => {
    const schema = schemaFromFields([
      field({ name: 'keyword', required: true, description: '搜索关键字' }),
      field({ name: 'level', type: 'integer', enumValues: '1, 2，3' }),
      field({ name: 'tags', type: 'array' }),
      field({ name: '  ', type: 'boolean' }),
    ])

    expect(schema).toEqual({
      type: 'object',
      properties: {
        keyword: { type: 'string', description: '搜索关键字' },
        level: { type: 'integer', enum: [1, 2, 3] },
        tags: { type: 'array', items: { type: 'string' } },
      },
      required: ['keyword'],
    })
  })

  it('omits required when no field is required', () => {
    expect(schemaFromFields([field({})])).toEqual({ type: 'object', properties: { keyword: { type: 'string' } } })
  })
})

describe('fieldsFromSchema', () => {
  it('round-trips fields generated by the table', () => {
    const fields = [
      field({ name: 'keyword', required: true, description: '关键字' }),
      field({ name: 'mode', enumValues: 'fast, full' }),
      field({ name: 'enabled', type: 'boolean' }),
    ]

    expect(fieldsFromSchema(schemaFromFields(fields))).toEqual(fields)
  })

  it('reads external schemas defensively', () => {
    const fields = fieldsFromSchema({
      type: 'object',
      properties: { city: { type: ['string', 'null'] }, raw: 'invalid', payload: { type: 'object' } },
      required: ['city', 42],
    })

    expect(fields.map(item => [item.name, item.type, item.required])).toEqual([
      ['city', 'string', true],
      ['raw', 'string', false],
      ['payload', 'object', false],
    ])
    expect(fieldsFromSchema(null)).toEqual([])
  })
})

describe('validateFields', () => {
  it('reports invalid, reserved and duplicated names', () => {
    const errors = validateFields([
      field({ name: '1bad' }),
      field({ name: 'credential' }),
      field({ name: 'keyword' }),
      field({ name: 'keyword' }),
      field({ name: 'size', type: 'integer', enumValues: '1, 2.5' }),
    ])

    expect(errors).toHaveLength(4)
    expect(errors.join('\n')).toContain('凭据占位符')
    expect(errors.join('\n')).toContain('参数名称重复')
    expect(errors.join('\n')).toContain('可选值须为整数')
  })
})

describe('template helpers', () => {
  it('extracts placeholders in order without duplicates', () => {
    expect(placeholdersIn('https://api.test/{{city}}?q={{keyword}}', null, '{"a": {{keyword}}, "t": "{{credential}}"}'))
      .toEqual(['city', 'keyword', 'credential'])
  })

  it('validates body templates after replacing placeholders with null', () => {
    expect(isValidBodyTemplate('{"q": {{keyword}}, "size": {{size}}}')).toBe(true)
    expect(isValidBodyTemplate('{"q": {{keyword}')).toBe(false)
  })
})

describe('buildTestArguments', () => {
  it('converts typed inputs and reports missing or invalid values', () => {
    const fields = [
      field({ name: 'keyword', required: true }),
      field({ name: 'size', type: 'integer' }),
      field({ name: 'exact', type: 'boolean' }),
      field({ name: 'tags', type: 'array' }),
      field({ name: 'note' }),
    ]

    const valid = buildTestArguments(fields, { keyword: ' 订单 ', size: '20', exact: true, tags: '["a"]', note: '' })
    expect(valid).toEqual({ arguments: { keyword: '订单', size: 20, exact: true, tags: ['a'] }, errors: [] })

    const invalid = buildTestArguments(fields, { keyword: '', size: '1.5', exact: false, tags: '{"a":1}', note: '' })
    expect(invalid.errors).toEqual(['keyword：必填参数未填写', 'size：请输入整数', 'tags：请输入 JSON 数组，例如 ["a", "b"]'])
  })
})
